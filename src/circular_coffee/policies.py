class LLMCommunicationPolicy:
    def __init__(
        self,
        client: LLMClient,
        *,
        system_prompt: str = COMMUNICATION_SYSTEM_PROMPT,
        prompt_version: str = "communication_v1",
    ) -> None:
        self._client = client
        self._system_prompt = system_prompt
        self._prompt_version = prompt_version
        self._last_llm_log: dict[str, Any] | None = None

    def choose_communication_action(
        self,
        observation: dict,
    ) -> CommunicationAction:
        raw: AgentAction | CommunicationAction | dict | str | None = None
        parse_error = None
        validation_error = None
        api_error = None
        action: CommunicationAction | None = None
        try:
            raw = self._client.generate_action(self._system_prompt, observation)
            payload = json.loads(raw) if isinstance(raw, str) else raw
            if isinstance(payload, dict) and set(payload) == {"action"}:
                payload = payload["action"]
            if isinstance(payload, CommunicationAction):
                action = payload
            elif isinstance(payload, dict):
                unknown = set(payload) - set(CommunicationAction.__dataclass_fields__)
                if unknown:
                    raise ValueError(
                        f"unknown communication fields: {sorted(unknown)}"
                    )
                action = CommunicationAction(**payload)
            else:
                raise TypeError("communication action must be an object")
            if action.action_type not in {"send_message", "no_message"}:
                raise ValueError("unsupported communication action")
        except json.JSONDecodeError as exc:
            parse_error = str(exc)
        except Exception as exc:
            validation_error = str(exc)
            if raw is None:
                api_error = str(exc)

        fallback_used = action is None
        if action is None:
            action = CommunicationAction(
                action_type="no_message",
                reason_summary="Invalid communication output fallback.",
            )
        metadata = getattr(self._client, "last_call_metadata", None) or {}
        self._last_llm_log = {
            "model": metadata.get("model"),
            "system_prompt_name": "communication_phase",
            "prompt_version": self._prompt_version,
            "parse_error": parse_error,
            "validation_error": validation_error,
            "fallback_used": fallback_used,
            "api_error": metadata.get("api_error") or api_error,
            "input_tokens": metadata.get("input_tokens", 0),
            "output_tokens": metadata.get("output_tokens", 0),
        }
        return action

    def consume_last_llm_log(self) -> dict[str, Any] | None:
        log = self._last_llm_log
        self._last_llm_log = None
        return log


class RandomPolicy:
    def __init__(self, seed: int = 0):
        self._rng = random.Random(seed)

    def choose_action(self, observation: dict) -> AgentAction:
        actions = [AgentAction(action_type="wait", reason_summary="Random wait.")]
        incoming = observation["incoming_pending_proposals"]
        for proposal in incoming:
            actions.append(
                AgentAction(
                    action_type="accept_trade",
                    proposal_id=proposal["proposal_id"],
                    reason_summary="Random acceptance.",
                )
            )
            actions.append(
                AgentAction(
                    action_type="reject_trade",
                    proposal_id=proposal["proposal_id"],
                    reason_summary="Random rejection.",
                )
            )
        inventory = observation["self"]["inventory"]
        if inventory:
            lot = next(iter(inventory.values()))
            counterparties = list(observation["other_agent_ids"])
            if counterparties:
                buyer_id = self._rng.choice(counterparties)
                markup = self._rng.choice([0.0, 0.1, 0.2, 0.3])
                actions.append(
                    AgentAction(
                        action_type="propose_trade",
                        seller_id=observation["self"]["agent_id"],
                        buyer_id=buyer_id,
                        lot_id=lot["lot_id"],
                        quantity=lot["quantity"],
                        unit_price=round(lot["carrying_unit_cost"] + 2.0 + markup, 2),
                        proposal_message="Would you like to buy this lot?",
                        reason_summary="Random resale offer.",
                    )
                )
        return self._rng.choice(actions)


class ScriptedCircularPolicy:
    _PRICE_MAP = {
        ("roaster", "retailer_a"): 10.5,
        ("retailer_a", "retailer_b"): 10.6,
        ("retailer_b", "roaster"): 10.7,
    }

    _NEXT_BUYER = {
        "roaster": "retailer_a",
        "retailer_a": "retailer_b",
        "retailer_b": "roaster",
    }

    def choose_action(self, observation: dict) -> AgentAction:
        agent_id = observation["self"]["agent_id"]
        day = observation["day"]
        incoming = observation["incoming_pending_proposals"]
        if incoming:
            return AgentAction(
                action_type="accept_trade",
                proposal_id=incoming[0]["proposal_id"],
                reason_summary="Accept scripted incoming proposal.",
            )
        inventory = observation["self"]["inventory"]
        if inventory:
            lot = next(iter(inventory.values()))
            expected_day = {"roaster": 1, "retailer_a": 3, "retailer_b": 5}[agent_id]
            if day == expected_day:
                next_buyer = self._NEXT_BUYER[agent_id]
                price = self._PRICE_MAP[(agent_id, next_buyer)]
                return AgentAction(
                    action_type="propose_trade",
                    seller_id=agent_id,
                    buyer_id=next_buyer,
                    lot_id=lot["lot_id"],
                    quantity=lot["quantity"],
                    unit_price=price,
                    proposal_message=f"Offering {lot['lot_id']} at {price:.1f} per unit.",
                    reason_summary="Advance scripted resale path.",
                )
        return AgentAction(action_type="wait", reason_summary="No scripted action available.")


class CooperativeRetailerPolicy:
    def __init__(
        self,
        *,
        preferred_buyers: list[str],
        resale_markup: float = 0.1,
        reproposal_cooldown_days: int = 4,
        max_purchase_unit_price: float | None = None,
        can_initiate_resale_to_roaster: bool = True,
        can_initiate_resale: bool = True,
    ):
        self._preferred_buyers = preferred_buyers
        self._resale_markup = resale_markup
        self._reproposal_cooldown_days = reproposal_cooldown_days
        self._max_purchase_unit_price = max_purchase_unit_price
        self._can_initiate_resale_to_roaster = can_initiate_resale_to_roaster
        self._can_initiate_resale = can_initiate_resale
        self._last_proposal_day_by_lot: dict[str, int] = {}

    def choose_action(self, observation: dict) -> AgentAction:
        cash = observation["self"]["cash"]
        incoming = observation["incoming_pending_proposals"]
        if incoming:
            proposal = incoming[0]
            total_price = proposal["quantity"] * proposal["unit_price"]
            if (
                self._max_purchase_unit_price is not None
                and proposal["unit_price"] > self._max_purchase_unit_price
            ):
                return AgentAction(
                    action_type="reject_trade",
                    proposal_id=proposal["proposal_id"],
                    reason_summary=PRICE_LIMIT_REJECTION_REASON,
                )
            if cash >= total_price:
                return AgentAction(
                    action_type="accept_trade",
                    proposal_id=proposal["proposal_id"],
                    reason_summary="Accept affordable inventory offer.",
                )
            return AgentAction(
                action_type="reject_trade",
                proposal_id=proposal["proposal_id"],
                reason_summary="Insufficient cash for proposed purchase.",
            )

        inventory = observation["self"]["inventory"] if self._can_initiate_resale else {}
        for lot in inventory.values():
            last_proposal_day = self._last_proposal_day_by_lot.get(lot["lot_id"])
            if (
                last_proposal_day is not None
                and observation["day"] - last_proposal_day < self._reproposal_cooldown_days
            ):
                continue
            buyer_id = next(
                (
                    candidate
                    for candidate in self._preferred_buyers
                    if self._can_initiate_resale_to_roaster or candidate != "roaster"
                    if candidate in observation["other_agent_ids"]
                ),
                None,
            )
            if buyer_id is None:
                break
            self._last_proposal_day_by_lot[lot["lot_id"]] = observation["day"]
            return AgentAction(
                action_type="propose_trade",
                seller_id=observation["self"]["agent_id"],
                buyer_id=buyer_id,
                lot_id=lot["lot_id"],
                quantity=lot["quantity"],
                unit_price=round(lot["carrying_unit_cost"] + self._resale_markup, 2),
                proposal_message="Inventory available for resale.",
                reason_summary="Offer held inventory to another participant.",
            )
        return AgentAction(action_type="wait", reason_summary="No trade opportunity available.")


class LLMPolicy:
    def __init__(
        self,
        client: LLMClient,
        *,
        condition: Literal[
            "profit_only",
            "revenue_pressure",
            "multi_strategy",
            "multi_strategy_profit_only",
            "multi_strategy_revenue_pressure",
        ],
        system_prompt: str | None = None,
        prompt_version: str = "v1",
    ):
        self._client = client
        self._condition = condition
        self._prompt_version = prompt_version
        self._system_prompt = system_prompt or build_llm_system_prompt(condition)
        self._last_llm_log: dict[str, Any] | None = None

    def choose_action(self, observation: dict) -> AgentAction:
        raw: AgentAction | dict | str | None = None
        api_call_error: str | None = None
        parse_error: str | None = None
        validation_error: str | None = None
        schema_payload_unwrapped = False
        legacy_action_normalized = False
        price_normalization = {
            "price_field_normalized": False,
            "original_price_field": None,
            "normalized_price_field": None,
        }
        fallback_used = False
        try:
            raw = self._client.generate_action(self._system_prompt, observation)
        except Exception as exc:
            payload = None
            api_call_error = str(exc)
        else:
            try:
                payload = json.loads(raw) if isinstance(raw, str) else raw
            except json.JSONDecodeError as exc:
                payload = None
                parse_error = str(exc)

        try:
            payload, schema_payload_unwrapped = self._unwrap_schema_payload(payload)
            payload, legacy_action_normalized = self._normalize_legacy_wait(payload)
            payload, price_normalization = self._normalize_price_fields(payload)
            action = self._validate_action(payload)
            self._validate_against_observation(action, observation)
        except (TypeError, ValueError) as exc:
            validation_error = str(exc)
            fallback_used = True
            action = AgentAction(
                action_type="wait",
                reason_summary="Invalid LLM output fallback.",
            )

        client_metadata = getattr(self._client, "last_call_metadata", None) or {}
        self._last_llm_log = {
            "model": client_metadata.get("model"),
            "temperature": client_metadata.get("temperature"),
            "system_prompt_name": self._condition,
            "prompt_version": self._prompt_version,
            "raw_response": raw if isinstance(raw, str) else client_metadata.get("raw_response", raw),
            "raw_llm_response": raw if isinstance(raw, str) else client_metadata.get("raw_response", raw),
            "parsed_action": asdict(action),
            "parse_error": parse_error,
            "validation_error": validation_error,
            "fallback_used": fallback_used,
            "schema_payload_unwrapped": schema_payload_unwrapped,
            "legacy_action_normalized": legacy_action_normalized,
            **price_normalization,
            "input_tokens": client_metadata.get("input_tokens", 0),
            "output_tokens": client_metadata.get("output_tokens", 0),
            "latency_ms": client_metadata.get("latency_ms", 0),
            "configured_max_retries": client_metadata.get("configured_max_retries", 0),
            "api_error": client_metadata.get("api_error") or api_call_error,
        }
        return action

    def consume_last_llm_log(self) -> dict[str, Any] | None:
        log = self._last_llm_log
        self._last_llm_log = None
        return log

    @staticmethod
    def _unwrap_schema_payload(payload: Any) -> tuple[Any, bool]:
        if (
            isinstance(payload, dict)
            and set(payload) == {"action"}
            and isinstance(payload["action"], dict)
        ):
            return payload["action"], True
        return payload, False

    @staticmethod
    def _normalize_price_fields(payload: Any) -> tuple[Any, dict[str, Any]]:
        return payload, {
            "price_field_normalized": False,
            "original_price_field": None,
            "normalized_price_field": None,
        }

    @staticmethod
    def _normalize_legacy_wait(payload: Any) -> tuple[Any, bool]:
        if isinstance(payload, AgentAction) and payload.action_type == "hold_inventory":
            return (
                AgentAction(
                    action_type="wait",
                    reason_summary=payload.reason_summary,
                    expected_outcome=payload.expected_outcome,
                ),
                True,
            )
        if isinstance(payload, dict) and payload.get("action_type") == "hold_inventory":
            normalized = dict(payload)
            normalized["action_type"] = "wait"
            return normalized, True
        return payload, False

    @staticmethod
    def _validate_action(payload: Any) -> AgentAction:
        if isinstance(payload, AgentAction):
            action = payload
        elif isinstance(payload, dict):
            unknown = set(payload) - set(AgentAction.__dataclass_fields__)
            if unknown:
                raise ValueError(f"unknown action fields: {sorted(unknown)}")
            action = AgentAction(**payload)
        else:
            raise TypeError("LLM client returned unsupported payload")
        if action.action_type not in ALLOWED_ACTION_TYPES:
            raise ValueError(f"unsupported action_type: {action.action_type}")
        required = {
            "propose_trade": (
                "seller_id",
                "buyer_id",
                "lot_id",
                "quantity",
                "unit_price",
            ),
            "accept_trade": ("proposal_id",),
            "reject_trade": ("proposal_id",),
            "accept_counteroffer": ("counteroffer_id",),
            "reject_counteroffer": ("counteroffer_id",),
            "counteroffer_trade": ("proposal_id", "unit_price"),
            "sell_to_consumer": ("lot_id", "quantity", "unit_price"),
            "wait": (),
        }[action.action_type]
        missing = [name for name in required if getattr(action, name) is None]
        if missing:
            raise ValueError(f"missing required fields: {', '.join(missing)}")
        return action

    @staticmethod
    def _validate_against_observation(action: AgentAction, observation: dict) -> None:
        if not observation:
            return
        self_view = observation["self"]
        if action.action_type == "propose_trade":
            candidates = [
                *observation.get("trade_candidates", {}).get("sell", []),
                *observation.get("trade_candidates", {}).get("buy", []),
            ]
            if not any(
                candidate["seller_id"] == action.seller_id
                and candidate["buyer_id"] == action.buyer_id
                and candidate["lot_id"] == action.lot_id
                and candidate["quantity"] == action.quantity
                for candidate in candidates
            ):
                raise ValueError("trade proposal is not an available candidate")
            if action.unit_price is None or action.unit_price <= 0:
                raise ValueError("unit_price must be positive")
        elif action.action_type == "sell_to_consumer":
            if not observation.get("market_access", {}).get(
                "can_sell_to_consumer",
                False,
            ):
                raise ValueError("consumer_sale_not_available")
            if not observation["market_information"].get("consumer_market_enabled", False):
                raise ValueError("consumer market is not enabled")
            lot = self_view["inventory"].get(action.lot_id)
            if lot is None:
                raise ValueError("agent does not own consumer-sale lot")
            if action.quantity != lot["quantity"]:
                raise ValueError("quantity must match full lot quantity")
            if action.unit_price is None or action.unit_price <= 0:
                raise ValueError("unit_price must be positive")
        elif action.action_type in {"accept_counteroffer", "reject_counteroffer"}:
            counteroffers = {
                item["counteroffer_id"]: item
                for item in observation.get("incoming_trade_counteroffers", [])
            }
            counteroffer = counteroffers.get(action.counteroffer_id)
            if counteroffer is None:
                raise ValueError("counteroffer is not pending for this agent")
            if (
                action.action_type == "accept_counteroffer"
                and counteroffer["buyer_id"] == self_view["agent_id"]
            ):
                total_price = counteroffer["quantity"] * counteroffer["unit_price"]
                if self_view["cash"] < total_price:
                    raise ValueError("insufficient cash for counteroffer")
        elif action.action_type in {"accept_trade", "reject_trade"}:
            proposals = {
                proposal["proposal_id"]: proposal
                for proposal in observation["incoming_pending_proposals"]
            }
            proposal = proposals.get(action.proposal_id)
            if proposal is None:
                raise ValueError("proposal is not an incoming pending proposal")
            if (
                action.action_type == "accept_trade"
                and proposal["buyer_id"] == self_view["agent_id"]
            ):
                total_price = proposal["quantity"] * proposal["unit_price"]
                if self_view["cash"] < total_price:
                    raise ValueError("insufficient cash for proposed purchase")


class RetailerMarketPolicy:
    """LLM policy for a Retailer's normal turn when the outside option is enabled."""

    policy_mode = "llm"

    def __init__(
        self,
        client: LLMClient,
        *,
        system_prompt: str = RETAILER_MARKET_SYSTEM_PROMPT,
        prompt_version: str = "retailer_consumer_v1",
    ) -> None:
        self._client = client
        self._system_prompt = system_prompt
        self._prompt_version = prompt_version
        self._last_llm_log: dict[str, Any] | None = None

    def choose_action(self, observation: dict) -> AgentAction:
        raw: AgentAction | dict | str | None = None
        parse_error = None
        validation_error = None
        api_error = None
        action = None
        legacy_action_normalized = False
        try:
            raw = self._client.generate_action(self._system_prompt, observation)
            payload = json.loads(raw) if isinstance(raw, str) else raw
            if isinstance(payload, dict) and set(payload) == {"action"}:
                payload = payload["action"]
            if not isinstance(payload, dict):
                raise TypeError("Retailer market action must be an object")
            action_name = payload.get("action")
            if action_name == "hold_inventory":
                action_name = "wait"
                legacy_action_normalized = True
            reason = payload.get("reason")
            expected_outcome = payload.get("expected_outcome")
            if action_name not in {
                "accept_trade",
                "reject_trade",
                "counteroffer_trade",
                "accept_counteroffer",
                "reject_counteroffer",
                "propose_trade",
                "sell_to_consumer",
                "wait",
            }:
                raise ValueError("unsupported Retailer market action")
            if not isinstance(reason, str) or not reason.strip():
                raise ValueError("reason must be a non-empty string")
            lot_id = payload.get("lot_id")
            quantity = payload.get("quantity")
            proposal_id = payload.get("proposal_id")
            counteroffer_id = payload.get("counteroffer_id")
            unit_price = payload.get("unit_price")
            seller_id = payload.get("seller_id")
            buyer_id = payload.get("buyer_id")
            if action_name in {
                "accept_trade",
                "reject_trade",
                "counteroffer_trade",
            }:
                proposals = {
                    item["proposal_id"]: item
                    for item in observation["incoming_pending_proposals"]
                }
                if proposal_id not in proposals:
                    raise ValueError("proposal_id must identify a pending incoming proposal")
                proposal = proposals[proposal_id]
                if (
                    action_name == "accept_trade"
                    and proposal["buyer_id"] == observation["retailer_id"]
                ):
                    total_price = proposal["quantity"] * proposal["unit_price"]
                    if observation["cash"] < total_price:
                        raise ValueError("Retailer has insufficient cash for the proposal")
                if action_name == "counteroffer_trade":
                    if (
                        not isinstance(unit_price, (int, float))
                        or not math.isfinite(unit_price)
                        or unit_price <= 0
                    ):
                        raise ValueError("counteroffer unit_price must be positive")
            if action_name in {"accept_counteroffer", "reject_counteroffer"}:
                counteroffers = {
                    item["counteroffer_id"]: item
                    for item in observation["incoming_trade_counteroffers"]
                }
                if counteroffer_id not in counteroffers:
                    raise ValueError(
                        "counteroffer_id must identify a pending incoming counteroffer"
                    )
                counteroffer = counteroffers[counteroffer_id]
                if (
                    action_name == "accept_counteroffer"
                    and counteroffer["buyer_id"] == observation["retailer_id"]
                    and observation["cash"]
                    < counteroffer["quantity"] * counteroffer["unit_price"]
                ):
                    raise ValueError("Retailer has insufficient cash for counteroffer")
            if action_name == "sell_to_consumer":
                owned = {item["lot_id"]: item for item in observation["inventory"]}
                if lot_id not in owned:
                    raise ValueError("Retailer does not own lot")
                if not isinstance(quantity, int) or quantity <= 0:
                    raise ValueError("quantity must be a positive integer")
                if quantity != owned[lot_id]["quantity"]:
                    raise ValueError("quantity must match the full lot")
                market = observation["consumer_market"]
                if not market["enabled"] or market["remaining_demand_today"] < quantity:
                    raise ValueError("consumer market cannot satisfy this sale")
            if action_name == "propose_trade":
                candidates = [
                    *observation.get("trade_candidates", {}).get("sell", []),
                    *observation.get("trade_candidates", {}).get("buy", []),
                ]
                if not any(
                    item["seller_id"] == seller_id
                    and item["buyer_id"] == buyer_id
                    and item["lot_id"] == lot_id
                    and item["quantity"] == quantity
                    for item in candidates
                ):
                    raise ValueError("trade proposal is not an available candidate")
                if (
                    not isinstance(unit_price, (int, float))
                    or not math.isfinite(unit_price)
                    or unit_price <= 0
                ):
                    raise ValueError("unit_price must be positive")
            action = AgentAction(
                action_type=action_name,
                seller_id=seller_id,
                buyer_id=buyer_id,
                proposal_id=proposal_id,
                counteroffer_id=counteroffer_id,
                lot_id=lot_id,
                quantity=quantity,
                unit_price=float(unit_price) if unit_price is not None else None,
                reason_summary=reason,
                expected_outcome=expected_outcome,
            )
        except json.JSONDecodeError as exc:
            parse_error = str(exc)
        except Exception as exc:
            validation_error = str(exc)
            if raw is None:
                api_error = str(exc)

        fallback_used = action is None
        if action is None:
            action = AgentAction(
                action_type="wait",
                reason_summary="Invalid Retailer LLM output fallback.",
            )
        metadata = getattr(self._client, "last_call_metadata", None) or {}
        self._last_llm_log = {
            "model": metadata.get("model"),
            "system_prompt_name": "independent_retailer_market_decision",
            "prompt_version": self._prompt_version,
            "raw_response": raw,
            "parsed_action": asdict(action),
            "parse_error": parse_error,
            "validation_error": validation_error,
            "fallback_used": fallback_used,
            "legacy_action_normalized": legacy_action_normalized,
            "api_error": metadata.get("api_error") or api_error,
            "input_tokens": metadata.get("input_tokens", 0),
            "output_tokens": metadata.get("output_tokens", 0),
        }
        return action

    def consume_last_llm_log(self) -> dict[str, Any] | None:
        log = self._last_llm_log
        self._last_llm_log = None
        return log


def policy_name(policy: AgentPolicy) -> str:
    return policy.__class__.__name__


def action_as_dict(action: AgentAction) -> dict:
    return asdict(action)
